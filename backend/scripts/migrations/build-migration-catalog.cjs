// Builds supabase/checks/migration_catalog.json: the catalog each active
// migration leaves behind, captured on a clean LOCAL database (Etapa 1B.2).
//
//   MIGRATION_CHECK_PG_URL=postgres://postgres:postgres@127.0.0.1:55432/postgres \
//     node scripts/migrations/build-migration-catalog.cjs          (from backend/)
//
// Run it whenever a migration is added (never to "fix" an applied one: applied
// migration files must not change). The manifest is versioned with the code.
//
// Safety: only localhost URLs are accepted. The script creates its own
// database (rs_migration_catalog_<random>), drops only that database, creates
// the Supabase API roles only if they are missing and drops only the roles it
// created. It never connects to a Supabase project.
const crypto = require('node:crypto');
const fs = require('node:fs');
const {
  MANIFEST_FILE, activeMigrations, readCatalogQuery, rowsToMap, deltaBetween,
  isLocalUrl, redactUrl, duplicateVersions, loadPg, SUPABASE_ROLE_SETUP, SUPABASE_DATABASE_SETUP,
} = require('./lib.cjs');

const API_ROLES = ['anon', 'authenticated', 'service_role'];

async function buildManifest(serverUrl, { log = console.log } = {}) {
  if (!serverUrl) throw new Error('Set MIGRATION_CHECK_PG_URL to a LOCAL PostgreSQL server.');
  if (!isLocalUrl(serverUrl)) throw new Error(`REFUSED: ${new URL(serverUrl).hostname} is not a local host.`);
  const files = activeMigrations();
  const duplicates = duplicateVersions(files);
  if (duplicates.length) {
    throw new Error(`REFUSED: duplicate migration versions: ${duplicates.map((d) => `${d.version} (${d.items.join(', ')})`).join('; ')}.`);
  }
  const { Client } = loadPg();
  const database = `rs_migration_catalog_${crypto.randomBytes(4).toString('hex')}`;
  const admin = new Client({ connectionString: serverUrl });
  await admin.connect();
  const missingRoles = (await admin.query('select unnest($1::text[]) as role except select rolname from pg_roles', [API_ROLES]))
    .rows.map((row) => row.role);
  await admin.query(SUPABASE_ROLE_SETUP);
  await admin.query(`create database ${database}`);
  const target = new URL(serverUrl);
  target.pathname = `/${database}`;
  const client = new Client({ connectionString: target.toString() });
  try {
    await client.connect();
    await client.query(SUPABASE_DATABASE_SETUP);
    const postgres = (await client.query('show server_version')).rows[0].server_version;
    const catalogQuery = readCatalogQuery();
    let previous = rowsToMap((await client.query(catalogQuery)).rows);
    if (previous.size !== 0) throw new Error('The clean database already has application objects.');
    const migrations = [];
    for (const migration of files) {
      await client.query(fs.readFileSync(migration.path, 'utf8'));
      const current = rowsToMap((await client.query(catalogQuery)).rows);
      const delta = deltaBetween(previous, current);
      migrations.push({ version: migration.version, name: migration.name, sha256: migration.sha256, ...delta });
      log(`${migration.version} ${migration.name}: +${Object.keys(delta.added).length} ~${Object.keys(delta.changed).length} -${delta.removed.length}`);
      if (!Object.keys(delta.added).length && !Object.keys(delta.changed).length && !delta.removed.length) {
        log(`  WARNING: ${migration.version} leaves no trace in catalog_objects.sql. db:migrations:check will report AMBIGUOUS`
          + ' for it until the CLI history records it; consider adding a `data` marker for its effect to the catalog query.');
      }
      previous = current;
    }
    return {
      description: 'Expected catalog per active migration (Etapa 1B.2). Generated by scripts/migrations/build-migration-catalog.cjs; do not edit by hand.',
      catalog_query: 'supabase/checks/catalog_objects.sql',
      built_on_postgres: postgres.split(' ')[0],
      object_count: previous.size,
      migrations,
    };
  } finally {
    await client.end().catch(() => {});
    await admin.query(`drop database if exists ${database} with (force)`).catch(() => {});
    for (const role of missingRoles) await admin.query(`drop role if exists ${role}`).catch(() => {});
    await admin.end();
  }
}

if (require.main === module) {
  const url = process.env.MIGRATION_CHECK_PG_URL;
  const out = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out') + 1] : MANIFEST_FILE;
  buildManifest(url)
    .then((manifest) => {
      fs.writeFileSync(out, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
      console.log(`Wrote ${out} (${manifest.migrations.length} migrations, ${manifest.object_count} objects, built on ${redactUrl(url)}).`);
    })
    .catch((error) => {
      console.error(error.message);
      process.exit(1);
    });
}

module.exports = { buildManifest };
