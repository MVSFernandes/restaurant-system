-- Per-order stock ledger with atomic create, edit, cancel and delete.
--
-- Before this migration the backend changed stock for an order through
-- separate calls (restore_order_stock / consume_order_stock, then UPDATE or
-- DELETE). Two requests could return the same stock twice, a failure between
-- calls left order and stock out of step, and every return was recalculated
-- from the CURRENT recipe instead of what the sale had actually taken.
--
-- What this migration does:
--
-- 1. order_stock_movements records every quantity an order flow actually took
--    (OUT) or returned (IN). Only real stock changes are recorded; estimates
--    are never written here. A return gives back exactly the outstanding
--    balance (OUT minus IN), under a lock on the order row, so a repeated or
--    concurrent return gives back nothing.
--
-- 2. create, edit, cancel and delete run in one transaction each
--    (create_order_with_stock, update_order_items_with_stock,
--    cancel_order_with_stock, delete_order_with_stock).
--
-- 3. Guard triggers refuse cancelling (status -> CANCELED), deleting an order,
--    or changing its items outside those functions, and the legacy
--    consume_order_stock / restore_order_stock are no longer executable by the
--    API roles. Old code paths therefore fail instead of bypassing the ledger.
--
-- 4. Orders that exist when this migration first runs have no ledger: what
--    they took cannot be reconstructed, because recipes may have changed or
--    been removed since the sale and edits re-consumed stock with the recipe of
--    their own time. They are listed once in order_stock_legacy_reviews with
--    an ESTIMATE (current recipe at migration time), clearly labelled as such.
--    The migration does not change any stock balance. Cancelling a listed
--    order no longer returns stock automatically: a person decides through
--    resolve_legacy_order_stock (return the estimate, return counted amounts,
--    or return nothing). Replacing the items of a listed order is always
--    refused (cancel and launch again); deleting it is refused while the
--    review is pending. See docs/REVISAO_ETAPA_1A.md.
--
-- Re-running the file is harmless: objects use IF NOT EXISTS / OR REPLACE and
-- the legacy listing only happens on the first run (order_stock_ledger_rollout).
begin;

set local search_path = public, extensions, pg_catalog;

