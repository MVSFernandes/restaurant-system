-- Takes stock for the given items and records what was actually taken.
-- Same conversion as consume_order_stock: weight / 1000 for by-weight
-- products, quantity otherwise. The caller must hold the order row lock.
create or replace function public.consume_stock_for_order(p_order_id text, p_items jsonb, p_reason text)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_status text;
  v_need record;
  v_before numeric;
  v_after numeric;
  v_name text;
  v_movements jsonb := '[]'::jsonb;
  v_missing_product text;
begin
  select status into v_status from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'ORDER_NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_status = 'CANCELED' then
    raise exception 'ORDER_ALREADY_CANCELED' using errcode = 'P0001';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    return jsonb_build_object('movements', v_movements);
  end if;

  select item->>'product_id' into v_missing_product
  from jsonb_array_elements(p_items) as item
  where not exists (select 1 from public.products as product where product.id = item->>'product_id')
  limit 1;
  if found then
    raise exception 'Produto não encontrado: %', v_missing_product using errcode = 'P0002';
  end if;

  for v_need in
    with item as (
      select
        product.id as product_id,
        case when product.is_by_weight
          then coalesce((entry->>'weight')::numeric, 0) / 1000.0
          else coalesce((entry->>'quantity')::numeric, 1)
        end as multiplier
      from jsonb_array_elements(p_items) as entry
      join public.products as product on product.id = entry->>'product_id'
    )
    select link.stock_item_id, sum(link.quantity * item.multiplier) as amount
    from item
    join public.product_stock_items as link on link.product_id = item.product_id
    where item.multiplier > 0
    group by link.stock_item_id
    having sum(link.quantity * item.multiplier) > 0
    order by link.stock_item_id
  loop
    select quantity, name into v_before, v_name
    from public.stock_items
    where id = v_need.stock_item_id
    for update;

    begin
      update public.stock_items
      set quantity = quantity - v_need.amount
      where id = v_need.stock_item_id
      returning quantity into v_after;
    exception
      when check_violation then
        raise exception 'Estoque insuficiente do insumo "%" (id=%)', v_name, v_need.stock_item_id
          using errcode = 'P0001';
    end;

    -- Record the effective change, after the column's rounding.
    if v_before - v_after > 0 then
      insert into public.order_stock_movements (order_id, order_ref, stock_item_id, direction, quantity, reason)
      values (p_order_id, p_order_id, v_need.stock_item_id, 'OUT', v_before - v_after, p_reason);
      v_movements := v_movements || jsonb_build_object(
        'stock_item_id', v_need.stock_item_id, 'quantity', v_before - v_after
      );
    end if;
  end loop;

  return jsonb_build_object('movements', v_movements);
end;
$function$;

-- Returns the outstanding balance of an order (OUT minus IN) and records it.
-- Repeating the call returns nothing, because the balance is then zero.
create or replace function public.restore_stock_for_order(p_order_id text, p_reason text)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_balance record;
  v_movements jsonb := '[]'::jsonb;
begin
  perform 1 from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'ORDER_NOT_FOUND' using errcode = 'P0002';
  end if;

  for v_balance in
    select
      movement.stock_item_id,
      sum(case movement.direction when 'OUT' then movement.quantity else -movement.quantity end) as outstanding
    from public.order_stock_movements as movement
    where movement.order_id = p_order_id
    group by movement.stock_item_id
    having sum(case movement.direction when 'OUT' then movement.quantity else -movement.quantity end) > 0
    order by movement.stock_item_id
  loop
    update public.stock_items
    set quantity = quantity + v_balance.outstanding
    where id = v_balance.stock_item_id;

    insert into public.order_stock_movements (order_id, order_ref, stock_item_id, direction, quantity, reason)
    values (p_order_id, p_order_id, v_balance.stock_item_id, 'IN', v_balance.outstanding, p_reason);

    v_movements := v_movements || jsonb_build_object(
      'stock_item_id', v_balance.stock_item_id, 'quantity', v_balance.outstanding
    );
  end loop;

  return jsonb_build_object('movements', v_movements);
end;
$function$;

create or replace function public.order_has_pending_legacy_stock_review(p_order_id text)
 returns boolean
 language sql
 stable
 security definer
 set search_path to 'public'
as $function$
  select exists (
    select 1 from public.order_stock_legacy_reviews
    where order_id = p_order_id and resolution = 'PENDING'
  );
$function$;

-- True for every order listed by the transition, whatever the review decided.
-- What a listed order took from stock is unknown, so its items can never be
-- replaced through the ledger: returning "nothing outstanding" and taking the
-- new items would deduct the same stock twice.
create or replace function public.order_is_legacy_stock_order(p_order_id text)
 returns boolean
 language sql
 stable
 security definer
 set search_path to 'public'
as $function$
  select exists (select 1 from public.order_stock_legacy_reviews where order_id = p_order_id);
$function$;

