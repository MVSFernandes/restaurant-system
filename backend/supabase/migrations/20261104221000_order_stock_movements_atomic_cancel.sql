create or replace function public.guard_order_stock_operation()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_operation text := coalesce(current_setting('app.order_stock_operation', true), '');
begin
  if tg_table_name = 'orders' then
    if tg_op = 'DELETE' then
      if v_operation <> 'delete' then
        raise exception 'ORDER_STOCK_OPERATION_REQUIRED'
          using errcode = 'P0001', detail = 'delete_order_with_stock';
      end if;
      return old;
    end if;
    if v_operation <> 'cancel' then
      raise exception 'ORDER_STOCK_OPERATION_REQUIRED'
        using errcode = 'P0001', detail = 'cancel_order_with_stock';
    end if;
    return new;
  end if;

  if v_operation not in ('create', 'edit', 'delete') then
    raise exception 'ORDER_STOCK_OPERATION_REQUIRED'
      using errcode = 'P0001', detail = 'order_items';
  end if;
  return coalesce(new, old);
end;
$function$;

drop trigger if exists trg_guard_order_cancel on public.orders;
create trigger trg_guard_order_cancel
  before update of status on public.orders
  for each row
  when (new.status = 'CANCELED' and old.status is distinct from 'CANCELED')
  execute function public.guard_order_stock_operation();

drop trigger if exists trg_guard_order_delete on public.orders;
create trigger trg_guard_order_delete
  before delete on public.orders
  for each row execute function public.guard_order_stock_operation();

drop trigger if exists trg_guard_order_items on public.order_items;
create trigger trg_guard_order_items
  before insert or update or delete on public.order_items
  for each row execute function public.guard_order_stock_operation();

