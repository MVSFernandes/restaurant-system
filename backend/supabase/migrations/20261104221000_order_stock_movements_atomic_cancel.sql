create table if not exists public.order_stock_movements (
  id bigint generated by default as identity primary key,
  -- order_id becomes null if the order is deleted; order_ref keeps the trail.
  order_id text references public.orders(id) on delete set null,
  order_ref text not null,
  -- RESTRICT: a stock item with recorded movements cannot be physically
  -- deleted, so its history is never lost (the API answers 409).
  stock_item_id text not null references public.stock_items(id) on delete restrict,
  direction text not null,
  quantity numeric not null,
  reason text not null,
  created_at timestamp with time zone not null default now(),
  constraint order_stock_movements_direction_check check (direction in ('OUT', 'IN')),
  constraint order_stock_movements_quantity_check check (quantity > 0),
  constraint order_stock_movements_reason_check check (reason in (
    'ORDER_CREATED', 'ORDER_EDITED', 'ORDER_CANCELED', 'ORDER_DELETED', 'LEGACY_REVIEW_RETURN'
  ))
);

create index if not exists idx_order_stock_movements_order_stock
  on public.order_stock_movements (order_id, stock_item_id);
create index if not exists idx_order_stock_movements_order_ref
  on public.order_stock_movements (order_ref);
create index if not exists idx_order_stock_movements_stock_item
  on public.order_stock_movements (stock_item_id);

comment on table public.order_stock_movements is
  'Real stock taken (OUT) and returned (IN) by order flows. Never contains estimates.';

create table if not exists public.order_stock_legacy_reviews (
  order_ref text primary key,
  order_id text unique references public.orders(id) on delete set null,
  status_at_migration text not null,
  order_created_at timestamp with time zone not null,
  items_snapshot jsonb not null,
  estimated_return jsonb not null,
  estimate_basis text not null default 'CURRENT_RECIPE_AT_MIGRATION',
  items_without_current_recipe integer not null default 0,
  resolution text not null default 'PENDING',
  order_event text,
  order_event_at timestamp with time zone,
  resolved_by text,
  resolved_at timestamp with time zone,
  resolution_note text,
  applied_return jsonb,
  listed_at timestamp with time zone not null default now(),
  constraint order_stock_legacy_reviews_resolution_check check (resolution in (
    'PENDING', 'RETURNED_ESTIMATE', 'RETURNED_COUNTED', 'NO_RETURN'
  )),
  constraint order_stock_legacy_reviews_event_check check (order_event is null or order_event = 'CANCELED'),
  constraint order_stock_legacy_reviews_resolved_check check (
    resolution = 'PENDING'
    or (resolved_at is not null and nullif(btrim(resolved_by), '') is not null
        and nullif(btrim(resolution_note), '') is not null)
  )
);

comment on table public.order_stock_legacy_reviews is
  'Orders created before the stock ledger. estimated_return is an estimate from the recipe at migration time, not a record of what was consumed.';

create table if not exists public.order_stock_ledger_rollout (
  id boolean primary key default true,
  started_at timestamp with time zone not null default now(),
  legacy_orders_listed integer not null,
  constraint order_stock_ledger_rollout_single_row check (id)
);

