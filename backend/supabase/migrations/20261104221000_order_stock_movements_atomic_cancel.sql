-- ---------------------------------------------------------------------------
-- Transition: list orders created before the ledger (first run only)
-- ---------------------------------------------------------------------------
--
-- Listed: every order that is not CANCELED when the ledger starts. Being
-- listed is NOT a statement that stock was taken; it only means the order can
-- still be cancelled (ADMIN/CASHIER may cancel any non-canceled order), edited
-- (NEW) or deleted, and there is no record of what it took.
-- Not listed: CANCELED orders. They cannot be reopened, and their stock path
-- already ran under the previous flow; nothing will touch their stock again.
do $transition$
begin
  if not exists (select 1 from public.order_stock_ledger_rollout) then
    insert into public.order_stock_legacy_reviews (
      order_ref, order_id, status_at_migration, order_created_at,
      items_snapshot, estimated_return, items_without_current_recipe
    )
    select
      order_row.id,
      order_row.id,
      order_row.status,
      order_row.created_at,
      coalesce((
        select jsonb_agg(jsonb_build_object(
          'product_id', item.product_id, 'product_name', item.product_name,
          'quantity', item.quantity, 'weight', item.weight
        ) order by item.id)
        from public.order_items as item
        where item.order_id = order_row.id
      ), '[]'::jsonb),
      coalesce((
        select jsonb_agg(jsonb_build_object('stock_item_id', estimate.stock_item_id, 'quantity', estimate.amount)
                         order by estimate.stock_item_id)
        from (
          select link.stock_item_id,
                 sum(link.quantity * case when product.is_by_weight
                   then coalesce(item.weight, 0) / 1000.0
                   else coalesce(item.quantity, 1)
                 end) as amount
          from public.order_items as item
          join public.products as product on product.id = item.product_id
          join public.product_stock_items as link on link.product_id = product.id
          where item.order_id = order_row.id
          group by link.stock_item_id
          having sum(link.quantity * case when product.is_by_weight
            then coalesce(item.weight, 0) / 1000.0
            else coalesce(item.quantity, 1)
          end) > 0
        ) as estimate
      ), '[]'::jsonb),
      (
        select count(*)::integer
        from public.order_items as item
        where item.order_id = order_row.id
          and not exists (
            select 1 from public.product_stock_items as link where link.product_id = item.product_id
          )
      )
    from public.orders as order_row
    where order_row.status <> 'CANCELED';

    insert into public.order_stock_ledger_rollout (id, started_at, legacy_orders_listed)
    values (true, now(), (select count(*) from public.order_stock_legacy_reviews));
  end if;
end;
$transition$;

commit;
