-- Cancels an order and returns its stock in one transaction.
-- p_required_status / p_required_waiter_id re-check, under the row lock, what
-- the caller validated before (a waiter may cancel only their own NEW order).
-- The cancellable states are the same as before this migration.
create or replace function public.cancel_order_with_stock(
  p_order_id text,
  p_required_status text default null,
  p_required_waiter_id text default null
)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_order public.orders%rowtype;
  v_restored jsonb := jsonb_build_object('movements', '[]'::jsonb);
  v_legacy boolean;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'ORDER_NOT_FOUND' using errcode = 'P0002';
  end if;

  if v_order.status = 'CANCELED' then
    -- A repeated cancel keeps reporting a review that is still pending.
    return jsonb_build_object(
      'order', to_jsonb(v_order), 'already_canceled', true,
      'restored', '[]'::jsonb,
      'stock_review_required', public.order_has_pending_legacy_stock_review(p_order_id)
    );
  end if;

  if (p_required_status is not null and v_order.status is distinct from p_required_status)
     or (p_required_waiter_id is not null and v_order.waiter_id is distinct from p_required_waiter_id) then
    raise exception 'ORDER_CANCEL_PRECONDITION_FAILED'
      using errcode = 'P0001', detail = v_order.status;
  end if;

  v_legacy := public.order_has_pending_legacy_stock_review(p_order_id);
  if v_legacy then
    -- No evidence of what this order took: nothing is returned automatically.
    update public.order_stock_legacy_reviews
    set order_event = 'CANCELED', order_event_at = now()
    where order_id = p_order_id;
  else
    v_restored := public.restore_stock_for_order(p_order_id, 'ORDER_CANCELED');
  end if;

  perform set_config('app.order_stock_operation', 'cancel', true);
  -- Existing triggers keep running here: pending payments are canceled and a
  -- settled table tab is closed, inside this same transaction.
  update public.orders set status = 'CANCELED' where id = p_order_id
  returning * into v_order;
  perform set_config('app.order_stock_operation', '', true);

  return jsonb_build_object(
    'order', to_jsonb(v_order),
    'already_canceled', false,
    'restored', v_restored->'movements',
    'stock_review_required', v_legacy
  );
end;
$function$;

-- Replaces the items of a NEW order and its stock in one transaction:
-- returns the outstanding balance, swaps the items, takes stock for the new
-- items and applies the order patch (total, delivery data, customer name).
-- Any failure leaves items, stock, ledger and order exactly as they were.
create or replace function public.update_order_items_with_stock(
  p_order_id text,
  p_items jsonb,
  p_order_patch jsonb default '{}'::jsonb,
  p_required_waiter_id text default null
)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_order public.orders%rowtype;
  v_patch jsonb := coalesce(p_order_patch, '{}'::jsonb);
  v_paused_product_name text;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'ORDER_NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_order.status <> 'NEW'
     or (p_required_waiter_id is not null and v_order.waiter_id is distinct from p_required_waiter_id) then
    raise exception 'ORDER_EDIT_PRECONDITION_FAILED' using errcode = 'P0001', detail = v_order.status;
  end if;
  -- Listed legacy orders: items stay locked, also after NO_RETURN (a decision
  -- about returns, not a proof of what was taken). Cancel and launch again.
  if public.order_is_legacy_stock_order(p_order_id) then
    raise exception 'LEGACY_ORDER_ITEMS_LOCKED' using errcode = 'P0001';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Adicione itens ao pedido';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_items) i
    where coalesce((i->>'quantity')::numeric, 0) <= 0
       or ((i->>'weight') is not null and (i->>'weight')::numeric <= 0)
       or i->>'order_id' is distinct from p_order_id
  ) then
    raise exception 'Itens ou quantidades inválidos';
  end if;

  perform 1
  from public.products as product
  where product.id in (select item->>'product_id' from jsonb_array_elements(p_items) as item)
  order by product.id
  for update;

  select product.name into v_paused_product_name
  from public.products as product
  where product.is_paused
    and product.id in (select item->>'product_id' from jsonb_array_elements(p_items) as item)
  order by product.name
  limit 1;
  if found then
    raise exception 'O produto "%" está pausado.', v_paused_product_name using errcode = 'P0001';
  end if;

  perform set_config('app.order_stock_operation', 'edit', true);
  perform public.restore_stock_for_order(p_order_id, 'ORDER_EDITED');
  delete from public.order_items where order_id = p_order_id;
  insert into public.order_items
  select * from jsonb_populate_recordset(null::public.order_items, p_items);
  perform public.consume_stock_for_order(p_order_id, p_items, 'ORDER_EDITED');
  perform set_config('app.order_stock_operation', '', true);

  update public.orders set
    total = case when v_patch ? 'total' then (v_patch->>'total')::numeric else total end,
    delivery_fee = case when v_patch ? 'delivery_fee' then (v_patch->>'delivery_fee')::numeric else delivery_fee end,
    delivery_type = case when v_patch ? 'delivery_type' then v_patch->>'delivery_type' else delivery_type end,
    customer_name = case when v_patch ? 'customer_name' then v_patch->>'customer_name' else customer_name end,
    delivery_street = case when v_patch ? 'delivery_street' then v_patch->>'delivery_street' else delivery_street end,
    delivery_number = case when v_patch ? 'delivery_number' then v_patch->>'delivery_number' else delivery_number end,
    delivery_neighborhood = case when v_patch ? 'delivery_neighborhood' then v_patch->>'delivery_neighborhood' else delivery_neighborhood end,
    delivery_reference = case when v_patch ? 'delivery_reference' then v_patch->>'delivery_reference' else delivery_reference end,
    delivery_phone = case when v_patch ? 'delivery_phone' then v_patch->>'delivery_phone' else delivery_phone end,
    delivery_notes = case when v_patch ? 'delivery_notes' then v_patch->>'delivery_notes' else delivery_notes end
  where id = p_order_id
  returning * into v_order;

  return to_jsonb(v_order);
end;
$function$;

-- Deletes an order in one transaction. As before, only active orders
-- (NEW, IN_PROGRESS, READY, DELIVERED) give their stock back. A foreign key
-- (invoice, credit charge) now aborts the whole delete instead of leaving a
-- half-deleted order.
create or replace function public.delete_order_with_stock(p_order_id text)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_order public.orders%rowtype;
  v_restored jsonb := jsonb_build_object('movements', '[]'::jsonb);
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'ORDER_NOT_FOUND' using errcode = 'P0002';
  end if;
  if public.order_has_pending_legacy_stock_review(p_order_id) then
    raise exception 'LEGACY_ORDER_STOCK_REVIEW_REQUIRED' using errcode = 'P0001';
  end if;

  if v_order.status in ('NEW', 'IN_PROGRESS', 'READY', 'DELIVERED') then
    v_restored := public.restore_stock_for_order(p_order_id, 'ORDER_DELETED');
  end if;

  perform set_config('app.order_stock_operation', 'delete', true);
  delete from public.payments where order_id = p_order_id;
  delete from public.order_items where order_id = p_order_id;
  delete from public.orders where id = p_order_id;
  perform set_config('app.order_stock_operation', '', true);

  return jsonb_build_object('order', to_jsonb(v_order), 'restored', v_restored->'movements');
end;
$function$;

-- Same function as in the base, except that stock is taken through
-- consume_stock_for_order after the order row exists, so the ledger records it.
create or replace function public.create_order_with_stock(p_order jsonb, p_items jsonb, p_payment jsonb default null::jsonb)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_order public.orders%rowtype;
  v_stock record;
  v_paused_product_name text;
begin
  if nullif(p_order->>'id', '') is null then
    raise exception 'Identificador do pedido obrigatório';
  end if;
  -- Scoped key is stored independently from the human-facing CUID.
  perform pg_advisory_xact_lock(hashtextextended(coalesce(nullif(p_order->>'idempotency_key', ''), p_order->>'id'), 0));
  if nullif(p_order->>'idempotency_key', '') is not null then
    select * into v_order from public.orders where idempotency_key = p_order->>'idempotency_key';
    if found then return to_jsonb(v_order); end if;
  end if;
  select * into v_order from public.orders where id = p_order->>'id';
  if found then return to_jsonb(v_order); end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Adicione itens ao pedido';
  end if;
  if jsonb_array_length(p_items) = 0 then
    raise exception 'Adicione itens ao pedido';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_items) i
    where coalesce((i->>'quantity')::numeric, 0) <= 0
       or ((i->>'weight') is not null and (i->>'weight')::numeric <= 0)
       or i->>'order_id' is distinct from p_order->>'id'
  ) then
    raise exception 'Itens ou quantidades inválidos';
  end if;

  -- Serialize pause changes with order creation for every referenced product.
  perform 1
  from public.products as product
  where product.id in (
    select item->>'product_id' from jsonb_array_elements(p_items) as item
  )
  order by product.id
  for update;

  select product.name
  into v_paused_product_name
  from public.products as product
  where product.is_paused
    and product.id in (
      select item->>'product_id' from jsonb_array_elements(p_items) as item
    )
  order by product.name
  limit 1;

  if found then
    raise exception 'O produto "%" está pausado.', v_paused_product_name
      using errcode = 'P0001';
  end if;

  -- Lock shared ingredients in a consistent order before checking/consuming.
  -- Keep the existing stock RPC's weight/unit conversion rules.
  for v_stock in
    select s.id, s.name, s.quantity from public.stock_items s
    where s.id in (
      select l.stock_item_id from public.product_stock_items l
      join jsonb_array_elements(p_items) i on l.product_id = i->>'product_id'
    )
    order by s.id for update
  loop
    if exists (
      select 1 from public.product_stock_items l
      join jsonb_array_elements(p_items) i on l.product_id = i->>'product_id'
      where l.stock_item_id = v_stock.id and l.quantity > v_stock.quantity
    ) then
      raise exception 'Estoque insuficiente de "%"', v_stock.name;
    end if;
  end loop;

  insert into public.orders
  select * from jsonb_populate_record(null::public.orders,
    p_order || jsonb_build_object('created_at', now(), 'updated_at', now()))
  returning * into v_order;

  perform set_config('app.order_stock_operation', 'create', true);
  insert into public.order_items
  select * from jsonb_populate_recordset(null::public.order_items, p_items);
  perform set_config('app.order_stock_operation', '', true);

  perform public.consume_stock_for_order(v_order.id, p_items, 'ORDER_CREATED');

  if v_order.type = 'DINE_IN' and v_order.table_id is not null then
    update public.tables set status = 'OCCUPIED' where id = v_order.table_id;
  end if;

  if p_payment is not null and p_payment <> 'null'::jsonb then
    if p_payment->>'order_id' is distinct from v_order.id then
      raise exception 'Pagamento não pertence ao pedido';
    end if;
    insert into public.payments
    select * from jsonb_populate_record(null::public.payments,
      p_payment || jsonb_build_object('created_at', now()));
  end if;
  return to_jsonb(v_order);
end;
$function$;

-- ---------------------------------------------------------------------------
-- Review of orders created before the ledger (run by an administrator in the
-- SQL editor; not exposed to the API roles)
-- ---------------------------------------------------------------------------

-- p_decision:
--   NO_RETURN        nothing goes back to stock (any order state). It is a
--                    decision about returns only: it does not confirm what
--                    the order took and does not unlock its items.
--   RETURN_ESTIMATE  return estimated_return (order must be CANCELED).
--   RETURN_COUNTED   return p_items [{stock_item_id, quantity}] that a person
--                    checked (order must be CANCELED).
-- A review is resolved once; author and note are mandatory.
create or replace function public.resolve_legacy_order_stock(
  p_order_ref text,
  p_decision text,
  p_resolved_by text,
  p_note text,
  p_items jsonb default null
)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_review public.order_stock_legacy_reviews%rowtype;
  v_status text;
  v_return jsonb;
  v_line record;
begin
  if nullif(btrim(coalesce(p_resolved_by, '')), '') is null or nullif(btrim(coalesce(p_note, '')), '') is null then
    raise exception 'LEGACY_REVIEW_REQUIRES_AUTHOR_AND_NOTE' using errcode = 'P0001';
  end if;

  select * into v_review from public.order_stock_legacy_reviews where order_ref = p_order_ref for update;
  if not found then
    raise exception 'LEGACY_REVIEW_NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_review.resolution <> 'PENDING' then
    raise exception 'LEGACY_REVIEW_ALREADY_RESOLVED' using errcode = 'P0001';
  end if;

  if p_decision = 'NO_RETURN' then
    update public.order_stock_legacy_reviews
    set resolution = 'NO_RETURN', resolved_by = p_resolved_by, resolved_at = now(),
        resolution_note = p_note, applied_return = '[]'::jsonb
    where order_ref = p_order_ref;
    return jsonb_build_object('order_ref', p_order_ref, 'resolution', 'NO_RETURN', 'applied_return', '[]'::jsonb);
  end if;

  if p_decision not in ('RETURN_ESTIMATE', 'RETURN_COUNTED') then
    raise exception 'LEGACY_REVIEW_INVALID_DECISION' using errcode = 'P0001';
  end if;

  select status into v_status from public.orders where id = v_review.order_id for update;
  if v_status is distinct from 'CANCELED' then
    raise exception 'LEGACY_REVIEW_RETURN_REQUIRES_CANCELED_ORDER' using errcode = 'P0001';
  end if;

  v_return := case when p_decision = 'RETURN_ESTIMATE' then v_review.estimated_return else p_items end;
  if v_return is null or jsonb_typeof(v_return) <> 'array' then
    raise exception 'LEGACY_REVIEW_INVALID_ITEMS' using errcode = 'P0001';
  end if;
  if exists (
    select 1 from jsonb_array_elements(v_return) as line
    where coalesce((line->>'quantity')::numeric, 0) <= 0
       or not exists (select 1 from public.stock_items as stock where stock.id = line->>'stock_item_id')
  ) then
    raise exception 'LEGACY_REVIEW_INVALID_ITEMS' using errcode = 'P0001';
  end if;

  for v_line in
    select line->>'stock_item_id' as stock_item_id, sum((line->>'quantity')::numeric) as quantity
    from jsonb_array_elements(v_return) as line
    group by line->>'stock_item_id'
    order by line->>'stock_item_id'
  loop
    update public.stock_items set quantity = quantity + v_line.quantity where id = v_line.stock_item_id;
    insert into public.order_stock_movements (order_id, order_ref, stock_item_id, direction, quantity, reason)
    values (v_review.order_id, p_order_ref, v_line.stock_item_id, 'IN', v_line.quantity, 'LEGACY_REVIEW_RETURN');
  end loop;

  update public.order_stock_legacy_reviews
  set resolution = case when p_decision = 'RETURN_ESTIMATE' then 'RETURNED_ESTIMATE' else 'RETURNED_COUNTED' end,
      resolved_by = p_resolved_by, resolved_at = now(), resolution_note = p_note, applied_return = v_return
  where order_ref = p_order_ref;

  return jsonb_build_object('order_ref', p_order_ref, 'resolution', p_decision, 'applied_return', v_return);
end;
$function$;

