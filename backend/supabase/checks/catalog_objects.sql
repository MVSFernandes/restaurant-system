-- Read-only fingerprint of the application catalog (Etapa 1B.2).
--
-- One row per object of the public schema that the migrations create or
-- change: tables, columns, constraints, indexes, functions (definition, owner
-- and EXECUTE for PUBLIC and the API roles), triggers, RLS flags, policies,
-- table privileges of the API roles, the extensions the base installs, and the
-- data rows a migration must leave behind (`data` category).
--
-- It only reads the catalog: no table, row, privilege or setting is changed.
-- `scripts/migrations/check-migration-state.cjs` runs it and compares the
-- result with `migration_catalog.json` (the expected state after each
-- migration, built from a clean database by build-migration-catalog.cjs).
--
-- Single statement on purpose, so it runs unchanged in the SQL editor, in
-- `supabase db query` and through a PostgreSQL driver.
with api_roles(role_name) as (
  values ('anon'), ('authenticated'), ('service_role')
),
public_tables as (
  select table_row.oid, table_row.relname, table_row.relkind, table_row.relrowsecurity, table_row.relforcerowsecurity
  from pg_class as table_row
  join pg_namespace as namespace on namespace.oid = table_row.relnamespace
  where namespace.nspname = 'public'
    and table_row.relkind in ('r', 'p')
),
catalog_objects(category, object_key, definition_hash) as (
  select 'tables', table_row.relname::text, md5(table_row.relname::text || '|' || table_row.relkind::text)
  from public_tables as table_row

  union all

  select
    'columns',
    table_row.relname::text || '.' || attribute.attname::text,
    md5(concat_ws(
      '|',
      table_row.relname,
      attribute.attnum::text,
      attribute.attname,
      format_type(attribute.atttypid, attribute.atttypmod),
      (not attribute.attnotnull)::text,
      coalesce(pg_get_expr(default_row.adbin, default_row.adrelid), 'null'),
      coalesce(case attribute.attidentity when 'a' then 'GENERATED ALWAYS' when 'd' then 'GENERATED BY DEFAULT' end, 'null'),
      coalesce(case attribute.attgenerated when 's' then 'STORED' when 'v' then 'VIRTUAL' end, 'null')
    ))
  from public_tables as table_row
  join pg_attribute as attribute on attribute.attrelid = table_row.oid
  left join pg_attrdef as default_row
    on default_row.adrelid = table_row.oid and default_row.adnum = attribute.attnum
  where attribute.attnum > 0
    and not attribute.attisdropped

  union all

  select
    'constraints',
    table_row.relname::text || '.' || constraint_row.conname::text,
    md5(concat_ws(
      '|',
      table_row.relname,
      constraint_row.conname,
      constraint_row.contype::text,
      constraint_row.convalidated::text,
      constraint_row.condeferrable::text,
      constraint_row.condeferred::text,
      pg_get_constraintdef(constraint_row.oid, true)
    ))
  from pg_constraint as constraint_row
  join public_tables as table_row on table_row.oid = constraint_row.conrelid
  where constraint_row.contype in ('p', 'u', 'f', 'c', 'x')

  union all

  select
    'indexes',
    table_row.relname::text || '.' || index_row.relname::text,
    md5(concat_ws(
      '|',
      table_row.relname,
      index_row.relname,
      index_meta.indisunique::text,
      index_meta.indisvalid::text,
      pg_get_indexdef(index_row.oid)
    ))
  from pg_index as index_meta
  join pg_class as index_row on index_row.oid = index_meta.indexrelid
  join public_tables as table_row on table_row.oid = index_meta.indrelid

  union all

  select
    'functions',
    procedure_row.proname::text || '(' || pg_get_function_identity_arguments(procedure_row.oid) || ')',
    md5(
      btrim(regexp_replace(pg_get_functiondef(procedure_row.oid), E'\r\n?', E'\n', 'g'), E' \t\n\r')
      || '|owner=' || pg_get_userbyid(procedure_row.proowner)
      || '|public=' || coalesce(procedure_row.proacl is null or exists (
           select 1 from aclexplode(procedure_row.proacl) as acl
           where acl.grantee = 0 and acl.privilege_type = 'EXECUTE'), false)::text
      || '|anon=' || has_function_privilege('anon', procedure_row.oid, 'EXECUTE')::text
      || '|authenticated=' || has_function_privilege('authenticated', procedure_row.oid, 'EXECUTE')::text
      || '|service_role=' || has_function_privilege('service_role', procedure_row.oid, 'EXECUTE')::text
    )
  from pg_proc as procedure_row
  join pg_namespace as namespace on namespace.oid = procedure_row.pronamespace
  where namespace.nspname = 'public'
    and procedure_row.prokind in ('f', 'p')
    and not exists (
      select 1
      from pg_depend as dependency
      where dependency.classid = 'pg_proc'::regclass
        and dependency.objid = procedure_row.oid
        and dependency.deptype = 'e'
    )

  union all

  select
    'triggers',
    table_row.relname::text || '.' || trigger_row.tgname::text,
    md5(btrim(pg_get_triggerdef(trigger_row.oid, true)) || '|' || trigger_row.tgenabled::text)
  from pg_trigger as trigger_row
  join public_tables as table_row on table_row.oid = trigger_row.tgrelid
  where not trigger_row.tgisinternal

  union all

  select
    'rls',
    table_row.relname::text,
    md5(table_row.relrowsecurity::text || '|' || table_row.relforcerowsecurity::text)
  from public_tables as table_row

  union all

  select
    'policies',
    policy.tablename::text || '.' || policy.policyname::text,
    md5(concat_ws(
      '|', policy.permissive, array_to_string(policy.roles, ','), policy.cmd,
      coalesce(policy.qual, 'null'), coalesce(policy.with_check, 'null')
    ))
  from pg_policies as policy
  where policy.schemaname = 'public'

  union all

  select
    'table_privileges',
    table_row.relname::text || '@' || api_roles.role_name,
    md5(concat_ws(
      ',',
      case when has_table_privilege(api_roles.role_name, table_row.oid, 'SELECT') then 'SELECT' end,
      case when has_table_privilege(api_roles.role_name, table_row.oid, 'INSERT') then 'INSERT' end,
      case when has_table_privilege(api_roles.role_name, table_row.oid, 'UPDATE') then 'UPDATE' end,
      case when has_table_privilege(api_roles.role_name, table_row.oid, 'DELETE') then 'DELETE' end,
      case when has_table_privilege(api_roles.role_name, table_row.oid, 'TRUNCATE') then 'TRUNCATE' end,
      case when has_table_privilege(api_roles.role_name, table_row.oid, 'REFERENCES') then 'REFERENCES' end,
      case when has_table_privilege(api_roles.role_name, table_row.oid, 'TRIGGER') then 'TRIGGER' end
    ))
  from public_tables as table_row
  cross join api_roles
  where exists (select 1 from pg_roles where rolname = api_roles.role_name)

  union all

  -- pg_trgm, which the base installs in public, by schema (versions differ
  -- between Supabase projects without changing the application). pgcrypto is
  -- not fingerprinted: every Supabase project already has it in `extensions`.
  select 'extensions', extension.extname::text, md5(extension.extname::text || '@' || namespace.nspname::text)
  from pg_extension as extension
  join pg_namespace as namespace on namespace.oid = extension.extnamespace
  where extension.extname = 'pg_trgm'

  union all

  -- Data a migration must leave behind. Only presence is fingerprinted, never
  -- the content; query_to_xml runs only when the table exists.
  select
    'data',
    'order_stock_ledger_rollout.rows',
    md5(case
      when to_regclass('public.order_stock_ledger_rollout') is null then 'no table'
      when (xpath('/row/n/text()', query_to_xml(
        'select count(*) as n from public.order_stock_ledger_rollout', false, true, '')))[1]::text = '1'
        then 'one row'
      else 'unexpected row count'
    end)
  where to_regclass('public.order_stock_ledger_rollout') is not null
)
select category, object_key, definition_hash
from catalog_objects
order by category, object_key;
